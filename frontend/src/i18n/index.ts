function initialLocale(): UiLocale {
  const saved = localStorage.getItem('ui_locale')
  if (saved === 'zh-CN' || saved === 'en-US') return saved
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en-US'
}

const currentLocale = ref<UiLocale>(initialLocale())

export const locale = readonly(currentLocale)
export const elementLocale = computed(() => currentLocale.value === 'zh-CN' ? zhCn : en)

export function translate(key: string, params: Params = {}) {
  const template = currentLocale.value === 'zh-CN' ? (zhMessages[key] || key) : key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? `{${name}}`))
}

export function setLocale(value: UiLocale) {
  currentLocale.value = value
  localStorage.setItem('ui_locale', value)
  document.documentElement.lang = value
}

export function toggleLocale() {
  setLocale(currentLocale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
}

export const i18n = {
  install(app: App) {
    app.config.globalProperties.$t = translate
    document.documentElement.lang = currentLocale.value
  },
}
